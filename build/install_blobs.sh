#!/usr/bin/env bash
#
# install_blobs.sh - install the validated QTI TEE blob set into the device
# tree and generate the make fragment that packs it into the ramdisk.
#
# The blobs themselves are NEVER committed (see .gitignore): this repository
# holds the extraction tooling, the manifest and the init service definitions,
# not Xiaomi/Qualcomm binaries.
#
# What it does, in order:
#   1. verifies vendor_blobs/MANIFEST.sha256 (sha256sum -c) - a tampered or
#      partially copied blob set is rejected before it can reach a build;
#   2. removes previously installed blob files (tracked in the generated
#      blob_install.mk) so a replaced firmware cannot leave stale libraries
#      behind;
#   3. copies vendor_blobs/system/** into
#      device/xiaomi/sakura/recovery/root/system/** with the mode the ramdisk
#      needs (0755 services, 0644 libraries);
#   4. re-validates every installed file (ELF, 64-bit AArch64, hash matches the
#      manifest) and writes device/xiaomi/sakura/blob_install.mk, a generated
#      PRODUCT_COPY_FILES fragment that device.mk includes with -include.
#
# If no blobs were extracted, this script says so, removes the generated
# fragment and exits non-zero: a build without the TEE chain cannot support
# decryption and must not silently pretend otherwise.
#
# Usage:
#   ./build/install_blobs.sh [--device-tree DIR] [--blobs DIR]
#   ./build/install_blobs.sh --clean
#
# SPDX-License-Identifier: Apache-2.0
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEV="${ROOT}/device/xiaomi/sakura"
BLOBS="${ROOT}/vendor_blobs"
CLEAN=0

while [ $# -gt 0 ]; do
    case "$1" in
        --device-tree) DEV="${2:-}"; shift 2 ;;
        --blobs)       BLOBS="${2:-}"; shift 2 ;;
        --clean)       CLEAN=1; shift ;;
        -h|--help)     sed -n '3,40p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "ERROR: unknown argument: $1" >&2; exit 2 ;;
    esac
done

die() { echo "ERROR: $*" >&2; exit 1; }
GEN="${DEV}/blob_install.mk"

remove_generated_files() {
    [ -f "$GEN" ] || return 0
    # Every PRODUCT_COPY_FILES destination generated by this script is a
    # recovery-ramdisk path; remove exactly those, nothing else.
    while IFS= read -r dst; do
        [ -n "$dst" ] || continue
        case "$dst" in
            recovery/root/system/bin/*|recovery/root/system/lib64/*)
                rm -f "${DEV}/${dst}"
                ;;
        esac
    done < <(sed -n 's/.*:\(recovery\/root\/system\/[^ ]*\).*/\1/p' "$GEN")
    rm -f "$GEN"
}

if [ "$CLEAN" = 1 ]; then
    remove_generated_files
    echo "==> removed installed blobs and $GEN"
    exit 0
fi

[ -d "$DEV" ] || die "no device tree at $DEV"
[ -f "${DEV}/proprietary-files.txt" ] || die "missing ${DEV}/proprietary-files.txt"

if [ ! -d "$BLOBS" ] || [ ! -f "${BLOBS}/MANIFEST.sha256" ]; then
    remove_generated_files
    cat >&2 <<EOF
ERROR: no extracted blob set found.

  expected: $BLOBS/MANIFEST.sha256

The QTI TEE chain (qseecomd, Keymaster 3.0, Gatekeeper 1.0 and their
libraries) is proprietary and cannot be committed or downloaded by this
repository. Extract it once from YOUR OWN sakura Android 9 stock fastboot ROM:

  ./build/extract_blobs.sh --firmware <sakura fastboot ROM>.tgz
  ./build/install_blobs.sh

Without that step the build cannot support decryption, so it is refused
rather than shipping an image that claims a feature it does not have.
EOF
    exit 1
fi

echo "==> verifying $BLOBS/MANIFEST.sha256"
( cd "$BLOBS" && sha256sum -c --quiet MANIFEST.sha256 ) || die \
    "blob checksum verification failed - re-run build/extract_blobs.sh from the original firmware"

echo "==> clearing any previously installed blobs"
remove_generated_files

echo "==> installing blobs into $DEV/recovery/root"
count=0
{
    echo "# GENERATED FILE - do not edit, do not commit (see .gitignore)."
    echo "# Written by build/install_blobs.sh from vendor_blobs/ extracted from a"
    echo "# user-supplied sakura stock firmware. Absent in a clean clone: device.mk"
    echo "# includes it with -include, so a build without blobs still configures and"
    echo "# is then refused by build/check_crypto_blobs.sh --require."
    echo
} > "$GEN"

while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    rel="${rel#./}"
    src="${BLOBS}/${rel}"
    [ -f "$src" ] || die "manifest lists $rel but $src is missing"
    case "$rel" in
        system/bin/*)      mode=0755 ;;
        system/lib64/*)    mode=0644 ;;
        *) die "unexpected blob path in manifest: $rel" ;;
    esac
    dst="${DEV}/recovery/root/${rel}"
    mkdir -p "$(dirname "$dst")"
    install -m "$mode" "$src" "$dst"

    python3 "${ROOT}/tools/elf.py" "$dst" >/dev/null 2>&1 || die \
        "$rel is not a valid ELF after install"
    info="$(python3 "${ROOT}/tools/elf.py" "$dst" 2>&1)"
    case "$info" in
        *"64-bit AArch64"*) ;;
        *) die "$rel has the wrong architecture: ${info//$'\n'/ }" ;;
    esac

    printf 'PRODUCT_COPY_FILES += $(DEVICE_PATH)/recovery/root/%s:recovery/root/%s\n' \
        "$rel" "$rel" >> "$GEN"
    count=$((count + 1))
done < <(grep -v '^#' "${BLOBS}/MANIFEST.sha256" | sed 's/^[0-9a-f]\{64\}  //' | sort)

[ "$count" -gt 0 ] || die "manifest contains no files"

echo "==> installed $count file(s); generated $(basename "$GEN")"
echo
echo "Next:"
echo "  ./build/run-all.sh            # or ./build/build.sh <source-tree>"
echo "Decryption remains UNTESTED until the built image is booted on a sakura"
echo "with encrypted /data. Extraction and installation are not a runtime test."
