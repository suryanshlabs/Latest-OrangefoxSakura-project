#!/usr/bin/env python3
"""
configure_metadata.py - opt-in metadata-encryption (FBEv2) configuration.

Why this is a separate, explicit step
------------------------------------
The pinned recovery *can* mount metadata-encrypted /data without any C++ change:

  * bootable/recovery Android.mk:360 adds -DTW_INCLUDE_FBE_METADATA_DECRYPT
    whenever TW_INCLUDE_CRYPTO is true, and Android.mk:139 links libvold, whose
    MetadataCrypt implements android::vold::fscrypt_mount_metadata_encrypted;
  * partition.cpp:193/220 parse `metadata_encryption=` and `keydirectory=`;
  * partitionmanager.cpp:677-700 mounts the key-directory partition and calls
    the metadata decrypt path when the /data partition has a key directory.

But partition.cpp Setup_Data_Partition() treats *any* non-empty Key_Directory as
"this /data is encrypted": it skips the crypto-footer check, sets
Is_Encrypted=true / Is_Decrypted=false and asks for a credential. On a device
whose ROM does not use metadata encryption that is a false encryption state, and
the user cannot mount /data at all. Every inspected sakura ROM fstab
(documentation/ENCRYPTION.md section 5) uses `fileencryption=ice` with no
metadata layer, and the vendor provides Keymaster 3.0 only, so wrapped-key
(FBEv2) support cannot be assumed.

Therefore metadata support ships *implemented* but disabled: this tool writes
the exact fstab/twrp.flags/build fragment a metadata-encrypted ROM needs, only
when a maintainer asks for it, and refuses to run without an explicit
acknowledgement that the target ROM uses metadata encryption.

What it writes
--------------
  recovery/root/system/etc/recovery.fstab
      * `/metadata` ext4 row (by-name/metadata), waited for at boot;
      * `metadata_encryption=aes-256-xts:wrappedkey_v0` and
        `keydirectory=/metadata/vold/metadata_encryption` appended to both
        /data rows, after the existing `formattable` token;
  recovery/root/system/etc/twrp.flags
      * a `/metadata` mount entry, so the TWRP partition list can mount it;
  device/xiaomi/sakura/metadata_encryption.mk
      * BOARD_USES_METADATA_PARTITION := true
      * PRODUCT_PROPERTY_OVERRIDES += ro.sakura.metadata_encryption=enabled

Every change is marked with `# sakura-metadata:` lines so `--disable` removes
exactly what `--enable` added and nothing else. `--enable` and `--disable` are
idempotent, and `--check` reports the current mode without writing.

Usage:
  tools/configure_metadata.py --device-tree DIR --enable --confirm-rom-uses-metadata
  tools/configure_metadata.py --device-tree DIR --disable
  tools/configure_metadata.py --device-tree DIR --check

Exit codes: 0 ok, 1 refused / inconsistent tree, 2 usage.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MARK = "# sakura-metadata:"

DATA_TOKENS = ("metadata_encryption=aes-256-xts:wrappedkey_v0",
               "keydirectory=/metadata/vold/metadata_encryption")

METADATA_FSTAB_ROW = (
    f"{MARK} metadata partition for FBEv2 key storage (opt-in)\n"
    "/dev/block/bootdevice/by-name/metadata         /metadata   ext4   "
    "nosuid,nodev,noatime,barrier=1            wait\n"
)

METADATA_FLAGS_ROW = (
    f"{MARK} metadata partition (opt-in; FBEv2 key directory)\n"
    "/metadata        ext4    /dev/block/bootdevice/by-name/metadata"
    "     flags=display=\"Metadata\"\n"
)

MK_BODY = """\
# {mark} GENERATED by tools/configure_metadata.py - do not edit, do not commit.
# Metadata-encrypted /data (FBEv2, wrappedkey_v0) is enabled for this build.
# Prerequisites: a ROM that actually uses metadata encryption, a metadata
# partition, and a TEE keymaster implementation with wrapped-key support.
# See documentation/ENCRYPTION.md section 6 before shipping this.
BOARD_USES_METADATA_PARTITION := true
PRODUCT_PROPERTY_OVERRIDES += ro.sakura.metadata_encryption=enabled
""".format(mark=MARK)


def read(path: str) -> str:
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def write(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def fstab_paths(device_tree: str) -> tuple[str, str]:
    root = os.path.join(device_tree, "recovery", "root", "system", "etc")
    return os.path.join(root, "recovery.fstab"), os.path.join(root, "twrp.flags")


def data_rows(text: str) -> list[str]:
    return [ln for ln in text.splitlines()
            if not ln.lstrip().startswith("#") and ln.split()
            and len(ln.split()) >= 5 and ln.split()[1] == "/data"]


def strip_metadata(text: str) -> str:
    """Remove everything --enable adds, leaving the original tree byte-identical.

    Only lines this tool could have written are touched: the marker comments,
    the /metadata rows, and /data rows that actually carry a metadata token.
    Everything else keeps its exact original bytes (including spacing), so an
    enable -> disable round trip is a no-op.
    """
    out: list[str] = []
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith(MARK):
            continue
        stripped = line.rstrip("\n")
        fields = stripped.split()
        is_meta_row = bool(fields) and not stripped.lstrip().startswith("#") and (
            fields[0] == "/metadata"
            or (len(fields) >= 5 and fields[1] == "/metadata"))
        if is_meta_row:
            continue
        if any(token in stripped for token in DATA_TOKENS):
            for token in DATA_TOKENS:
                stripped = stripped.replace("," + token, "")
                stripped = stripped.replace(token + ",", "")
                stripped = stripped.replace(token, "")
            stripped = re.sub(r",\s*$", "", stripped)
            line = stripped + "\n"
        out.append(line)
    return "".join(out)


def enable(device_tree: str) -> None:
    fstab, flags = fstab_paths(device_tree)
    for path in (fstab, flags):
        if not os.path.isfile(path):
            raise SystemExit(f"ERROR: missing {path}")

    # --- recovery.fstab -----------------------------------------------------
    text = strip_metadata(read(fstab))
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    inserted = False
    for line in lines:
        stripped = line.rstrip("\n")
        fields = stripped.split()
        if fields and not stripped.lstrip().startswith("#") and len(fields) >= 5 \
                and fields[1] == "/data":
            # Append after the last fs_mgr flag token.
            missing = [t for t in DATA_TOKENS if t not in fields[4].split(",")]
            if missing:
                stripped = stripped.rstrip() + "," + ",".join(missing)
                line = stripped + "\n"
        out.append(line)
        if not inserted and fields and not stripped.lstrip().startswith("#") \
                and len(fields) >= 5 and fields[1] == "/cache":
            out.append(METADATA_FSTAB_ROW)
            inserted = True
    if not inserted:
        raise SystemExit(f"ERROR: no /cache row in {fstab}; cannot place /metadata")
    write(fstab, "".join(out))

    # --- twrp.flags ---------------------------------------------------------
    text = strip_metadata(read(flags))
    lines = text.splitlines(keepends=True)
    out = []
    inserted = False
    for line in lines:
        out.append(line)
        fields = line.split()
        if not inserted and fields and not line.lstrip().startswith("#") \
                and fields[0] == "/cache":
            out.append(METADATA_FLAGS_ROW)
            inserted = True
    if not inserted:
        raise SystemExit(f"ERROR: no /cache row in {flags}; cannot place /metadata")
    write(flags, "".join(out))

    # --- generated make fragment -------------------------------------------
    write(os.path.join(device_tree, "metadata_encryption.mk"), MK_BODY)


def disable(device_tree: str) -> None:
    fstab, flags = fstab_paths(device_tree)
    write(fstab, strip_metadata(read(fstab)))
    write(flags, strip_metadata(read(flags)))
    mk = os.path.join(device_tree, "metadata_encryption.mk")
    if os.path.isfile(mk):
        os.remove(mk)


def status(device_tree: str) -> tuple[bool, list[str]]:
    problems: list[str] = []
    fstab, flags = fstab_paths(device_tree)
    text = read(fstab)
    rows = data_rows(text)
    enabled = bool(rows) and all(
        all(token in row.split()[4].split(",") for token in DATA_TOKENS)
        for row in rows)
    has_meta_row = any(
        ln.split() and not ln.lstrip().startswith("#")
        and len(ln.split()) >= 5 and ln.split()[1] == "/metadata"
        for ln in text.splitlines())
    mk = os.path.isfile(os.path.join(device_tree, "metadata_encryption.mk"))
    flags_has_meta = any(
        ln.split() and not ln.lstrip().startswith("#") and ln.split()[0] == "/metadata"
        for ln in read(flags).splitlines())

    if enabled != has_meta_row:
        problems.append("recovery.fstab: /data tokens and /metadata row disagree")
    if enabled and not mk:
        problems.append("metadata_encryption.mk missing while fstab enables metadata")
    if not enabled and mk:
        problems.append("metadata_encryption.mk present while fstab does not enable metadata")
    if enabled and not flags_has_meta:
        problems.append("twrp.flags has no /metadata entry")
    return enabled, problems


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--device-tree",
                    default=os.path.join(REPO_ROOT, "device", "xiaomi", "sakura"),
                    help="device tree to edit (default: this repository's "
                         "device/xiaomi/sakura)")
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--enable", action="store_true")
    group.add_argument("--disable", action="store_true")
    group.add_argument("--check", action="store_true")
    ap.add_argument("--confirm-rom-uses-metadata", action="store_true",
                    help="required with --enable: the target ROM really uses "
                         "metadata encryption (FBEv2). Without it recovery would "
                         "report a false encryption state on every other ROM.")
    args = ap.parse_args(argv[1:])

    tree = os.path.abspath(args.device_tree)
    if not os.path.isdir(tree):
        print(f"ERROR: {tree} is not a directory", file=sys.stderr)
        return 2

    if args.enable:
        if not args.confirm_rom_uses_metadata:
            print("ERROR: --enable requires --confirm-rom-uses-metadata.", file=sys.stderr)
            print("       Declaring keydirectory= makes the pinned recovery treat /data", file=sys.stderr)
            print("       as encrypted even when it is not (partition.cpp", file=sys.stderr)
            print("       Setup_Data_Partition). Enable only for a ROM that uses it.", file=sys.stderr)
            return 1
        enable(tree)
        enabled, problems = status(tree)
        if not enabled or problems:
            print("ERROR: metadata enablement is inconsistent:", file=sys.stderr)
            for p in problems:
                print(f"  - {p}", file=sys.stderr)
            return 1
        print("metadata encryption: ENABLED (FBEv2, wrappedkey_v0)")
        print("  /metadata row added to recovery.fstab and twrp.flags")
        print("  metadata_encryption.mk written (BOARD_USES_METADATA_PARTITION := true)")
        print("  Runtime decryption is STILL UNTESTED until a matching ROM boots.")
        return 0

    if args.disable:
        disable(tree)
        enabled, problems = status(tree)
        if enabled or problems:
            print("ERROR: metadata disablement left the tree inconsistent:", file=sys.stderr)
            for p in problems:
                print(f"  - {p}", file=sys.stderr)
            return 1
        print("metadata encryption: disabled (default)")
        return 0

    enabled, problems = status(tree)
    print(f"metadata encryption: {'ENABLED' if enabled else 'disabled'}")
    for p in problems:
        print(f"  [FAIL] {p}")
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
